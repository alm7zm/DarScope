-- The one table (docs/backend-plan.md, section 4). The same SQL runs on H2 and on Postgres.
-- IF NOT EXISTS lets the supabase profile run it at every start without harm.
CREATE TABLE IF NOT EXISTS property (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city               VARCHAR(20)  NOT NULL,
    district           VARCHAR(60)  NOT NULL,
    front              VARCHAR(20),
    property_type      VARCHAR(10)  NOT NULL,
    size_sqm           INTEGER      NOT NULL,
    property_age_years INTEGER      NOT NULL,
    bedrooms           INTEGER      NOT NULL,
    bathrooms          INTEGER      NOT NULL,
    living_rooms       INTEGER      NOT NULL,
    kitchen            BOOLEAN      NOT NULL DEFAULT FALSE,
    garage             BOOLEAN      NOT NULL DEFAULT FALSE,
    driver_room        BOOLEAN      NOT NULL DEFAULT FALSE,
    maid_room          BOOLEAN      NOT NULL DEFAULT FALSE,
    furnished          BOOLEAN      NOT NULL DEFAULT FALSE,
    ac                 BOOLEAN      NOT NULL DEFAULT FALSE,
    roof               BOOLEAN      NOT NULL DEFAULT FALSE,
    pool               BOOLEAN      NOT NULL DEFAULT FALSE,
    frontyard          BOOLEAN      NOT NULL DEFAULT FALSE,
    basement           BOOLEAN      NOT NULL DEFAULT FALSE,
    stairs             BOOLEAN      NOT NULL DEFAULT FALSE,
    elevator           BOOLEAN      NOT NULL DEFAULT FALSE,
    fireplace          BOOLEAN      NOT NULL DEFAULT FALSE,
    yearly_rent_sar    INTEGER      NOT NULL,
    description        VARCHAR(2000),
    status             VARCHAR(20)  NOT NULL,
    tenant_name        VARCHAR(80),
    lease_start        DATE,
    lease_end          DATE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL
);
